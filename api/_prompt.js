function buildSystemPrompt(page) {
  const pageBlock = page && page !== 'home' ? `\n<page>${page}</page>\nПользователь сейчас на странице этого кейса, ставь его в приоритет.` : '';
  return `${RULES}\n\n<knowledge>\n${knowledge}\n</knowledge>${pageBlock}`;
}

module.exports = { PAGES, buildSystemPrompt };
